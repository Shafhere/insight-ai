TOKEN_TTL = 60 * 60 * 12


def _db():
    return engine.begin()


def init_auth_store():
    with _db() as conn:
        conn.execute(text("""CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
            password_hash TEXT NOT NULL, role VARCHAR(16) NOT NULL, created_at BIGINT NOT NULL)""" if not DB_URL.startswith("sqlite") else """CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
            password_hash TEXT NOT NULL, role TEXT NOT NULL, created_at INTEGER NOT NULL)"""))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS reports (
            id VARCHAR(80) PRIMARY KEY, dataset_id VARCHAR(80) NOT NULL, title TEXT NOT NULL,
            payload TEXT NOT NULL, created_at BIGINT NOT NULL, published INTEGER NOT NULL DEFAULT 1)"""))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS access_codes (
            code_hash VARCHAR(64) PRIMARY KEY, report_id VARCHAR(80) NOT NULL,
            expires_at BIGINT, redeemed_by INTEGER, created_at BIGINT NOT NULL)"""))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS viewer_reports (
            user_id INTEGER NOT NULL, report_id VARCHAR(80) NOT NULL, PRIMARY KEY(user_id, report_id))"""))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS viewer_preferences (
            user_id INTEGER PRIMARY KEY, payload TEXT NOT NULL)"""))
        admin_email = settings.insight_admin_email.strip().lower()
        admin_password = settings.insight_admin_password
        existing = conn.execute(text("SELECT id FROM users WHERE email=:email"), {"email": admin_email}).first()
